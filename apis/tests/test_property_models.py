BASE_ROW: dict[str, Any] = {
    "name": "'Rose Cottage'",
    "address_line_1": "'1 High Street'",
    "locality": "'Bath'",
    "region": "'Somerset'",
    "country_code": "'GB'",
}


async def insert_raw(session_factory: Sessions, ids: dict[str, uuid.UUID], **columns: str) -> None:
    values = BASE_ROW | {
        "id": "gen_random_uuid()",
        "property_type_id": f"'{ids['residential']}'",
        "property_subtype_id": f"'{ids['house']}'",
    }
    for column, expression in columns.items():
        values[column] = expression.format(**{k: str(v) for k, v in ids.items()})
    async with session_factory() as db:
        columns_sql, values_sql = ", ".join(values), ", ".join(values.values())
        await db.execute(text(f"INSERT INTO properties ({columns_sql}) VALUES ({values_sql})"))
        await db.commit()


