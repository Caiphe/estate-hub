async def test_references_in_use_cannot_be_deleted(
    session_factory: Sessions, ids: dict[str, uuid.UUID]
) -> None:
    async with session_factory() as db:
        row = new_property(ids)
        row.amenities = [await db.get_one(Amenity, ids["parking"])]
        db.add(row)
        await db.commit()

    for table, key, constraint in (
        ("amenities", "parking", "fk_property_amenities_amenity_id_amenities"),
        ("property_subtypes", "house", "fk_properties_property_type_id_property_subtypes"),
        ("property_types", "residential", "fk_"),
    ):
        async with session_factory() as db:
            with pytest.raises(DBAPIError, match=constraint):
                await db.execute(text(f"DELETE FROM {table} WHERE id = '{ids[key]}'"))


async def test_amenity_links_are_unique_and_follow_the_property(
    session_factory: Sessions, ids: dict[str, uuid.UUID]
) -> None:
    async with session_factory() as db:
        row = new_property(ids)
        db.add(row)
        await db.commit()
        row_id = row.id

    link = property_amenities.insert().values(property_id=row_id, amenity_id=ids["garden"])
    async with session_factory() as db:
        await db.execute(link)
        await db.commit()
    async with session_factory() as db:
        with pytest.raises(DBAPIError, match="pk_property_amenities"):
            await db.execute(link)

    async with session_factory() as db:
        await db.execute(text(f"DELETE FROM properties WHERE id = '{row_id}'"))
        await db.commit()
        assert await db.scalar(text("SELECT count(*) FROM property_amenities")) == 0


