Sessions = async_sessionmaker[AsyncSession]


async def create_classification(session_factory: Sessions) -> dict[str, uuid.UUID]:
    """Two types with one subtype each, plus two amenities."""
    async with session_factory() as db:
        residential = PropertyType(name="Residential")
        residential.subtypes = [PropertySubtype(name="House")]
        commercial = PropertyType(name="Commercial")
        commercial.subtypes = [PropertySubtype(name="Office")]
        garden = Amenity(name="Garden", display_order=20)
        parking = Amenity(name="Parking", display_order=10)
        db.add_all([residential, commercial, garden, parking])
        await db.commit()
        return {
            "residential": residential.id,
            "house": residential.subtypes[0].id,
            "commercial": commercial.id,
            "office": commercial.subtypes[0].id,
            "garden": garden.id,
            "parking": parking.id,
        }


def new_property(ids: dict[str, uuid.UUID], **overrides: Any) -> Property:
    values: dict[str, Any] = {
        "name": "Rose Cottage",
        "property_type_id": ids["residential"],
        "property_subtype_id": ids["house"],
        "address_line_1": "1 High Street",
        "locality": "Bath",
        "region": "Somerset",
        "country_code": "GB",
    }
    return Property(**(values | overrides))


@pytest.fixture
async def ids(session_factory: Sessions) -> dict[str, uuid.UUID]:
    return await create_classification(session_factory)


