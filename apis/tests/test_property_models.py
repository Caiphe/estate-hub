async def test_classification_and_amenities_load_explicitly(
    session_factory: Sessions, ids: dict[str, uuid.UUID]
) -> None:
    async with session_factory() as db:
        garden = await db.get_one(Amenity, ids["garden"])
        parking = await db.get_one(Amenity, ids["parking"])
        row = new_property(ids)
        row.amenities = [garden, parking]
        db.add(row)
        await db.commit()
        row_id = row.id

    async with session_factory() as db:
        loaded = (
            await db.scalars(
                select(Property)
                .where(Property.id == row_id)
                .options(
                    selectinload(Property.property_type),
                    selectinload(Property.property_subtype),
                    selectinload(Property.amenities),
                )
            )
        ).one()

        assert loaded.property_type.name == "Residential"
        assert loaded.property_subtype is not None
        assert loaded.property_subtype.name == "House"
        # Amenities follow reference ordering: display_order, then name.
        assert [a.name for a in loaded.amenities] == ["Parking", "Garden"]

    async with session_factory() as db:
        unloaded = await db.get_one(Property, row_id)
        for attribute in ("property_type", "property_subtype", "amenities"):
            with pytest.raises(InvalidRequestError):
                getattr(unloaded, attribute)


