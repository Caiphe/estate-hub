# --- Archive visibility -----------------------------------------------------------------


async def test_archived_and_active_records_query_predictably(
    session_factory: Sessions, ids: dict[str, uuid.UUID]
) -> None:
    async with session_factory() as db:
        db.add_all(
            [
                new_property(ids, name="Draft", status=PropertyStatus.DRAFT),
                new_property(ids, name="Active", status=PropertyStatus.ACTIVE),
                new_property(ids, name="Inactive", status=PropertyStatus.INACTIVE),
                new_property(
                    ids,
                    name="Archived",
                    status=PropertyStatus.ARCHIVED,
                    archived_at=text("now()"),
                ),
            ]
        )
        await db.commit()

    async with session_factory() as db:
        unarchived = await db.scalars(
            select(Property.name)
            .where(Property.status != PropertyStatus.ARCHIVED)
            .order_by(Property.name, Property.id)
        )
        archived = (
            await db.scalars(select(Property).where(Property.status == PropertyStatus.ARCHIVED))
        ).one()

        assert list(unarchived) == ["Active", "Draft", "Inactive"]
        assert archived.is_archived
        assert archived.archived_at is not None
        assert await db.scalar(select(Property.id).where(Property.name == "Archived")) is not None


