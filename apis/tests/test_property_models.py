async def test_server_generates_reference_status_and_version(
    session_factory: Sessions, ids: dict[str, uuid.UUID]
) -> None:
    async with session_factory() as db:
        first, second = new_property(ids), new_property(ids, name="Ivy House")
        db.add_all([first, second])
        await db.commit()

        for row in (first, second):
            assert re.fullmatch(r"PR-\d{6}", row.reference)
            assert row.status == PropertyStatus.DRAFT
            assert row.version == 1
            assert row.archived_at is None
        assert first.reference != second.reference


