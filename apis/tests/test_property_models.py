async def test_updates_increment_version_and_stale_writers_fail(
    session_factory: Sessions, ids: dict[str, uuid.UUID]
) -> None:
    async with session_factory() as db:
        row = new_property(ids)
        db.add(row)
        await db.commit()
        row_id = row.id

    async with session_factory() as first, session_factory() as second:
        mine = await first.get_one(Property, row_id)
        theirs = await second.get_one(Property, row_id)

        mine.name = "Rose Cottage East"
        await first.commit()
        assert mine.version == 2

        theirs.name = "Rose Cottage West"
        with pytest.raises(StaleDataError):
            await second.commit()

    async with session_factory() as db:
        assert (await db.get_one(Property, row_id)).name == "Rose Cottage East"


